"""Hand cases for ``sc_source_oracle.py``'s CASSCF reference (#117): which
cases take ``--mo-from``, the refusal of an MO sidecar that does not belong to
the requested case -- every mismatch listed at once, through
``generate_golden._build_state``'s own fingerprint check -- and what the
committed ``*_casscf*.srcgold`` files claim about their partition.

The refusals run one RHF on N2/cc-pVDZ (about a second, no card) and stop
there: the fingerprint is checked before the CASCI. Nothing here differences
an energy; the oracle's numbers are regenerated byte for byte by
``devtools/golden-repro.sh`` and held to the GPU's on a card.
"""

from __future__ import annotations

import re

import golden_format as gf
import numpy as np
import pytest
import sc_source_oracle as so

CASE = "n2_ccpvdz_cas44_casscf"
GOLDEN = so.REPO / "golden"


def test_resolve_casscf_case_needs_mo_from():
    assert so.resolve_case(CASE, GOLDEN / f"{CASE}.mogold") == ("n2_ccpvdz_cas44", "casscf")
    with pytest.raises(SystemExit, match="needs --mo-from"):
        so.resolve_case(CASE, None)


def test_resolve_casci_case_refuses_mo_from():
    assert so.resolve_case("n2_ccpvdz_cas44", None) == ("n2_ccpvdz_cas44", "casci")
    with pytest.raises(SystemExit, match="belongs to a"):
        so.resolve_case("n2_ccpvdz_cas44", GOLDEN / f"{CASE}.mogold")


def test_every_casscf_case_has_its_inputs():
    cases = (set(so.ORACLE_CASES) | set(so.PC_ORACLE_CASES)
             | set(so.DIRECTIONAL_CASES["sc"]) | set(so.DIRECTIONAL_CASES["pc"]))
    casscf = sorted(c for c in cases if c.endswith(so.CASSCF_SUFFIX))
    assert casscf == [CASE]
    for c in casscf:
        base, _ = so.resolve_case(c, GOLDEN / f"{c}.mogold")
        assert base in so.ng.CASES
        assert (GOLDEN / f"{c}.mogold").exists() and (GOLDEN / f"{c}.nevpt2gold").exists()


def test_mismatched_sidecar_lists_every_mismatch(capsys):
    """LiF's sidecar for N2: every fingerprint field that differs, in one
    refusal -- the AO/MO counts, the partition, the atoms, the basis, the
    point group, the irrep selection and the geometry."""
    with pytest.raises(SystemExit) as e:
        so.rebuilt_state(CASE, pc=False, mo_from=GOLDEN / "lif_def2svp_cas46_casscf.mogold")
    msg = str(e.value)
    assert "was written for a different calculation" in msg
    for field in ("nao", "nmo", "ncore", "ncas", "symbols", "basis", "groupname",
                  "cas_irreps", "geometry"):
        assert re.search(rf"^  {field}: ", msg, re.MULTILINE), f"{field} not listed:\n{msg}"


def test_sidecar_differing_in_one_field_names_that_field():
    """N2's own density-fitted sidecar: the same molecule, basis and active
    space, so the auxiliary basis is the one line."""
    with pytest.raises(SystemExit) as e:
        so.rebuilt_state(CASE, pc=False, mo_from=GOLDEN / "n2_ccpvdz_cas44_casscf_df.mogold")
    lines = [ln for ln in str(e.value).splitlines() if ln.startswith("  ")]
    assert lines == ["  auxbasis: sidecar 'cc-pvdz-jkfit', this run ''"]


@pytest.mark.parametrize("scheme,flavour", [("sc", "full"), ("pc", "full"),
                                            ("sc", "directional"), ("pc", "directional")])
def test_committed_casscf_oracle_is_one_active_range(scheme, flavour):
    """No RHF partition on CASSCF orbitals (docs/gradient-theory.md, section
    1.4): the active space is one range, and the state is never rotated."""
    header, arrays = gf.read_srcgold(GOLDEN / gf.srcgold_name(CASE, scheme, flavour))
    assert header["n_act_occ"] == header["nact"]
    assert np.array_equal(arrays["act_rot"], np.eye(header["nact"]))
    if flavour == "directional":
        # No direction lies in a block that touches act_V (block 2 is
        # act_V's index in nevpt2_grad.SPACE_NAMES): it is empty.
        touches_act_v = [b for b, (s, t) in enumerate(so.BLOCKS) if 2 in (s, t)]
        assert not set(arrays["kappa_block"].astype(int)) & set(touches_act_v)
